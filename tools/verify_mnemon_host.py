"""Mount reviewed Mnemon host in an owned, credential-free candidate profile.

Prerequisite isolated dependency root .sumika-next/mnemon-host-deps; never
install its bundle/starter or use a daily profile. Model transport is loopback-only.
"""
import argparse
import json
import sys
import urllib.error
import urllib.request
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'tests_next'))
from p2_fixture import ModelFixture
from tools.verify_dsh_recovery import prompt, finish
from sumika_next.dsh import Dsh
from extensions.models.settings import example, save
from extensions.roles.chat import open_session


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--runtime', type=Path, default=ROOT/'runtime/dsh',
                        help='DSH runtime to verify (default: current pinned runtime)')
    args = parser.parse_args(argv)
    runtime = args.runtime.resolve()
    runtime_manifest = json.loads((runtime/'node_modules/@deepseek-ai/dsh/package.json').read_text(encoding='utf8'))
    runtime_version = runtime_manifest['version']
    dependency = ROOT / '.sumika-next/mnemon-host-deps/node_modules/dsh-mnemon'
    manifest = json.loads((dependency / 'package.json').read_text(encoding='utf8'))
    assert manifest['version'] == '0.5.29'
    base = ROOT / '.sumika-next' / ('mnemon-host-' + uuid.uuid4().hex)
    home = base / 'home'
    profile = home / 'profiles/web'
    profile.mkdir(parents=True)
    role = base / 'role'
    role.mkdir()
    (role / 'role.json').write_text(json.dumps(dict(id='fixture-role', name='Fixture',
        persona='Synthetic acceptance only', worldbook=[], assets={})), encoding='utf8')
    settings_path = base / 'settings.json'
    settings = example(role, base / 'canonical.sqlite3')
    save(settings, settings_path)
    session = open_session(settings, for_chat=True)
    try:
        session.memory.add('用户喜欢茉莉花茶', **session.scope)
    finally:
        session.close()
    fixture_config = dict(enabled=True, python=sys.executable,
        sdkEntry=str(dependency / 'lib/extension-sdk.js'), projects={str(base): str(settings_path)})
    fixture = base / 'source.mjs'
    fixture.write_text(
        'import { apply as applyCanonical } from ' + json.dumps((ROOT / 'extensions/memory/dsh.mjs').as_uri()) + ';\n'
        'export const name="sumika-memory-contract-fixture";\n'
        'export const inject=["mnemonMemory"];\n'
        'export function apply(ctx) { return applyCanonical(ctx,' + json.dumps(fixture_config) + '); }\n',
        encoding='utf8')
    config = dict(dataDir=str(base / 'data'), storageScope='workspace', writeEnabled=False,
                  lifecycleEnabled=True, recallMode='guided', writebackMode='off',
                  routingGuidance=False, tabEnabled=False, syncEnabled=False,
                  idleReview=dict(enabled=False, fallback='skip', maxPerSession=0),
                  conversationInteraction=dict(turnBar=False, saveAction=False, toolviews=False),
                  memoryView=dict(strategyTypeId='sumika-read-only', entries={}))
    patch = [dict(id='session-title-llm', disabled=True),
             dict(id='session-telemetry-otel', disabled=True),
             dict(insert=[dict(id='mnemon', name=str(dependency / 'lib/index.js'), config=config),
                          dict(id='sumika-contract-fixture', name=str(fixture))])]
    (profile / 'cordis.patch.yml').write_text(json.dumps(patch), encoding='utf8')
    adapter = Dsh(ROOT, home, runtime=runtime)
    model = ModelFixture()
    model.__enter__()
    patch.append(dict(id='llm-deepseek', config=dict(baseURL=model.url)))
    (home / '.env').write_text('DEEPSEEK_API_KEY=local-synthetic-fixture\n', encoding='utf8')
    (profile / 'cordis.patch.yml').write_text(json.dumps(patch), encoding='utf8')
    observations = []
    checks = {}

    def agent_turn(sid, *, expected_route, revoke_after_offer=False, cancel=False):
        model.responses = 0
        model.recipe = []
        model.block = True
        model.hold.clear()
        model.waiting.clear()
        adapter._rpc('session/create', dict(sessionId=sid, cwd=str(base)))
        stream = adapter.stream('session/follow', dict(address=dict(kind='session', sessionId=sid)), timeout=35)
        try:
            next(stream)
            prompt(adapter, sid, 'Synthetic test: recall my preferred tea using the offered memory route.')
            assert model.waiting.wait(20), 'Agent did not dispatch loopback model request'
            wire = json.dumps(model.requests[-1], ensure_ascii=False)
            # Parse only the quoted routing data generated by upstream Mnemon.
            texts = []
            def collect(value):
                if isinstance(value, str): texts.append(value)
                elif isinstance(value, dict):
                    for item in value.values(): collect(item)
                elif isinstance(value, list):
                    for item in value: collect(item)
            collect(model.requests[-1])
            routes = []
            for text in texts:
                marker = 'MNEMON VIEW ROUTES (quoted routing data; use mnemon_view_route or mnemon_view_action by exact id): '
                if marker in text:
                    offers, _ = json.JSONDecoder().raw_decode(text.split(marker, 1)[1])
                    routes.extend(route['id'] for source in offers for route in source['routes'])
            routes = list(dict.fromkeys(routes))
            assert bool(routes) == expected_route, (routes, wire)
            if routes:
                assert len(routes) == 1
                model.recipe = [('mnemon_view_route', dict(routeId=routes[0], input=dict(query='茉莉花茶')))]
            if revoke_after_offer:
                settings['memory']['enabled'] = False
                save(settings, settings_path)
            if cancel:
                assert adapter._rpc('session/cancel', dict(sessionId=sid)) == {'accepted': True}
            model.hold.set()
            events = finish(stream)
            observations.append(dict(operation=sid, events=events,
                                     model_requests=model.requests[-2:] if routes else model.requests[-1:]))
            return events
        finally:
            model.hold.set()
            model.block = False
            stream.close()
    def rpc(method, arguments):
        identity = uuid.uuid4().hex
        packet = dict(type='client-request', rpcId=identity, method=method,
                      payload=dict(args=arguments))
        request = urllib.request.Request(adapter.url + '/api/' + method,
            data=json.dumps(packet).encode(), headers={'Content-Type':'application/json', 'Origin':adapter.url})
        with adapter._opener.open(request, timeout=30) as response:
            result = json.load(response)
        assert result['rpcId'] == identity
        return result['result']
    try:
        adapter.start()
        plugins = rpc('pluginManager/listPlugins', {})
        observations.append(dict(operation='listPlugins', result=plugins))
        (base / 'observations.json').write_text(json.dumps(observations, indent=2), encoding='utf8')
        assert plugins['ok'], plugins
        row = next(row for row in plugins['value'] if row.get('patchId') == 'mnemon')
        assert row.get('enabled'), row
        dashboard = rpc('dshMnemon/view', dict(endpoint='dashboard', payload={}))
        observations.append(dict(operation='dashboard', result=dashboard))
        (base / 'observations.json').write_text(json.dumps(observations, indent=2), encoding='utf8')
        assert dashboard['ok'], dashboard
        value = dashboard['value']
        assert value['ok'], value
        assert len(value['value']['sources']) == 1, value
        assert value['value']['sources'][0]['sourceTypeId'] == 'sumika-canonical', value
        events = agent_turn('mnemon-read', expected_route=True)
        assert '用户喜欢茉莉花茶' in json.dumps(events, ensure_ascii=False), events
        checks['real_agent_route_reads_canonical_fact'] = True
        assert not any(e.get('event', {}).get('type') == 'tool/call' and
            e['event'].get('data', {}).get('name') == 'mnemon_view_action' for e in events)
        checks['real_agent_no_write_action'] = True
        settings['memory']['enabled'] = False
        save(settings, settings_path)
        events = agent_turn('mnemon-disabled', expected_route=False)
        assert '用户喜欢茉莉花茶' not in json.dumps(events, ensure_ascii=False)
        checks['real_agent_memory_off_no_route_or_text'] = True
        settings['memory']['enabled'] = True
        save(settings, settings_path)
        events = agent_turn('mnemon-revoke-old-offer', expected_route=True, revoke_after_offer=True)
        assert '用户喜欢茉莉花茶' not in json.dumps(events, ensure_ascii=False)
        checks['real_agent_revoke_old_offer_no_text'] = True
        settings['memory']['enabled'] = True
        save(settings, settings_path)
        events = agent_turn('mnemon-cancel', expected_route=True, cancel=True)
        assert '用户喜欢茉莉花茶' not in json.dumps(events, ensure_ascii=False)
        assert any(e.get('event', {}).get('type') == 'turn/end' and
            e['event'].get('data', {}).get('reason') == {'kind': 'aborted', 'reason': {'kind': 'user'}}
            for e in events), 'Expected native user-aborted turn/end'
        assert not any(e.get('event', {}).get('type') == 'tool/call' for e in events)
        checks['real_agent_cancel_before_route_no_text'] = True
        source_row = next(row for row in plugins['value'] if row.get('patchId') == 'sumika-contract-fixture')
        toggle = rpc('pluginManager/setPluginEnabled', dict(id=source_row['entryId'], enabled=False))
        observations.append(dict(operation='disableSource', result=toggle))
        assert toggle['ok'], toggle
        adapter.close()
        adapter.start()
        disabled = rpc('dshMnemon/view', dict(endpoint='dashboard', payload={}))
        observations.append(dict(operation='dashboardAfterDisableAndRestart', result=disabled))
        (base / 'observations.json').write_text(json.dumps(observations, indent=2), encoding='utf8')
        assert disabled['ok'] and disabled['value']['ok'], disabled
        assert disabled['value']['value']['sources'] == [], disabled
        report = dict(passed=True, mnemon='0.5.29', dsh=runtime_version, runtime=str(runtime),
            checks=dict(host_loaded=True, remote_dashboard=True, custom_source_registered=True,
                        no_builtin_sources=True, disabled_source_removed_after_restart=True, **checks),
            external_model_calls=0, daily_profile_changed=False,
            loopback_fixture_calls=len(model.requests),
            limits=['Real settings-bound wrapper, synthetic data; daily profile unchanged',
                    'Deterministic loopback fixture verifies wiring, not model quality or UI acceptance'])
        (base / 'report.json').write_text(json.dumps(report, indent=2), encoding='utf8')
        print(json.dumps(report))
    finally:
        adapter.close()
        model.hold.set()
        model.__exit__(None, None, None)
        # This owned profile contains only synthetic configuration and plugin metadata.
        (base / 'startup.log').write_text('\n'.join(adapter.startup_messages), encoding='utf8')
        print(f'Evidence: {base}')


if __name__ == '__main__':
    main()
